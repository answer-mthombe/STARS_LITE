import type { ClassRegisterModel } from "@/models/ClassRegister";
import type { TestRegisterModel } from "@/models/TestSession";

function formatDt(iso: string) {
  try {
    return new Date(iso).toLocaleString("en-ZA", {
      dateStyle: "medium",
      timeStyle: "short",
    });
  } catch {
    return iso;
  }
}

function tableRows(
  rows: { fullName: string; studentNumber: string; present: boolean; extra?: string }[],
  withExtra: boolean
): string {
  return rows
    .map(
      (r, i) => `
    <tr>
      <td>${i + 1}</td>
      <td>${escapeHtml(r.studentNumber)}</td>
      <td>${escapeHtml(r.fullName)}</td>
      <td>${r.present ? "Present" : "Absent"}</td>
      ${withExtra ? `<td>${escapeHtml(r.extra ?? "")}</td>` : ""}
    </tr>`
    )
    .join("");
}

function escapeHtml(s: string) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

const baseStyles = `
  body { font-family: Helvetica, Arial, sans-serif; padding: 24px; color: #1a1a1a; }
  h1 { color: #4F1A1D; font-size: 20px; margin: 0 0 4px; }
  h2 { color: #006281; font-size: 14px; margin: 0 0 16px; font-weight: 600; }
  .meta { font-size: 12px; line-height: 1.6; margin-bottom: 20px; }
  table { width: 100%; border-collapse: collapse; font-size: 11px; }
  th { background: #006281; color: #fff; text-align: left; padding: 8px; }
  td { border-bottom: 1px solid #ddd; padding: 6px 8px; }
  .footer { margin-top: 24px; font-size: 10px; color: #666; }
`;

export function classRegisterHtml(reg: ClassRegisterModel): string {
  const tutors = reg.tutorNames.length ? reg.tutorNames.join(", ") : "—";
  const rows = reg.students.map((s) => ({
    fullName: s.fullName,
    studentNumber: s.studentNumber,
    present: s.present,
  }));
  return `<!DOCTYPE html><html><head><meta charset="utf-8"/><style>${baseStyles}</style></head><body>
  <h1>MUT — Class attendance register</h1>
  <h2>${escapeHtml(reg.moduleCode)} · ${escapeHtml(reg.moduleName)}</h2>
  <div class="meta">
    <p><strong>Lecturer:</strong> ${escapeHtml(reg.lecturerName)}</p>
    <p><strong>Tutor(s):</strong> ${escapeHtml(tutors)}</p>
    <p><strong>Started:</strong> ${formatDt(reg.startedAt)}</p>
    <p><strong>Ended:</strong> ${formatDt(reg.endedAt)}</p>
    <p><strong>Duration:</strong> ${reg.durationMinutes} minutes</p>
  </div>
  <table>
    <thead><tr><th>#</th><th>Student no.</th><th>Name</th><th>Status</th></tr></thead>
    <tbody>${tableRows(rows, false)}</tbody>
  </table>
  <p class="footer">Generated by STARS · MUT Innovation Lab · ${formatDt(new Date().toISOString())}</p>
</body></html>`;
}

export function testRegisterHtml(reg: TestRegisterModel): string {
  const invig = reg.invigilatorNames.length ? reg.invigilatorNames.join(", ") : "—";
  const rows = reg.students.map((s) => ({
    fullName: s.fullName,
    studentNumber: s.studentNumber,
    present: s.present,
    extra: s.markedBy ?? (s.present ? "—" : ""),
  }));
  return `<!DOCTYPE html><html><head><meta charset="utf-8"/><style>${baseStyles}</style></head><body>
  <h1>MUT — Test / exam register</h1>
  <h2>${escapeHtml(reg.title)}</h2>
  <div class="meta">
    <p><strong>Lecturer:</strong> ${escapeHtml(reg.lecturerName)}</p>
    <p><strong>Invigilator(s):</strong> ${escapeHtml(invig)}</p>
    <p><strong>Started:</strong> ${formatDt(reg.startedAt)}</p>
    <p><strong>Ended:</strong> ${formatDt(reg.endedAt)}</p>
  </div>
  <table>
    <thead><tr><th>#</th><th>Student no.</th><th>Name</th><th>Status</th><th>Marked by</th></tr></thead>
    <tbody>${tableRows(rows, true)}</tbody>
  </table>
  <p class="footer">Generated by STARS · MUT Innovation Lab · ${formatDt(new Date().toISOString())}</p>
</body></html>`;
}
